function Model_A_validate_parameters(p)
names = Model_A_parameter_fields();
for k=1:numel(names)
    v=p.(names{k});
    assert(isnumeric(v)&&isscalar(v)&&isreal(v)&&isfinite(v), ...
        'Model_A:BadParameter','%s must be a finite real scalar.',names{k});
end
positive={'baseMVA','freq','M','K','xL2','VS','Ithresh','Imax', ...
 'SigmaXR','Vmax','omegaVI','tStop','maxStep','relTol','absTol', ...
 'initTol','residualTol'};
for k=1:numel(positive)
    assert(p.(positive{k})>0,'Model_A:BadParameter','%s must be positive.',positive{k});
end
assert(p.xe>=0 && p.xL1>=0 && p.xe+p.xL1>0 && p.KVI>=0 && ...
 p.xvmax>=0 && p.D>=0 && p.Dq>=0,'Model_A:BadParameter', ...
 'Reactances, damping and VI settings are invalid.');
assert(ismember(p.faultEnabled,[0,1])&&ismember(p.faultLoadToZ,[0,1]), ...
 'Model_A:BadParameter','Fault switches must be 0 or 1.');
assert(p.tFault>=0 && p.tClear>p.tFault,'Model_A:BadParameter', ...
 'Require 0 <= tFault < tClear.');
assert(~p.faultEnabled || (p.Rf>=0 && abs(complex(p.Rf,p.Xf))>0), ...
 'Model_A:BadParameter','Use finite, nonzero fault impedance (Rf >= 0).');
assert(~p.faultLoadToZ || p.Vswitch>0,'Model_A:BadParameter', ...
 'Vswitch must be positive when conversion is enabled.');
assert(ismember(p.solver,{'ode15s','ode23t','ode23tb','ode45'}), ...
 'Model_A:BadParameter','Unsupported solver; choose ode15s, ode23t, ode23tb or ode45.');
end
